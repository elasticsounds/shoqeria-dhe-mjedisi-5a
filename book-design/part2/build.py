class Page:
    """State while one spec runs."""
    def __init__(self, n):
        self.n = n; self.pid = f'pg{n:03d}'; self.texts = {}; self.speech = {}; self.sections = []; self.toc = []
        self.tn = 0; self.imn = 0; self.fn = 0; self.cur = None; self.lesson = ''; self.keys = {}; self.mc = {}; self.ms = {}; self.open = False

P = None  # current page

def _id():
    P.tn += 1; return f'{P.pid}_n{P.tn:04d}'

def T(text, easy=None, tag='span', cls=None, speech=None):
    """Register one sentence/heading and return its element. easy = easy-read version (body text and questions)."""
    i = _id(); P.texts[i] = text; P.speech[i] = speech if speech is not None else text
    if easy is not None: P.texts[i + '_easy_read'] = easy; P.speech[i + '_easy_read'] = easy
    c = f' class="{cls}"' if cls else ''
    return f'<{tag}{c} data-id="{i}">{H.escape(text, quote=False)}</{tag}>', i

def t(text, easy=None, **kw): return T(text, easy, **kw)[0]

def para(*sentences):
    """sentences: 'text' or ('text', 'easy-read text')."""
    return '<p>' + ' '.join(t(*s) if isinstance(s, tuple) else t(s) for s in sentences) + '</p>'

def img(file, alt, cls=None):
    """file is relative to images/ (crop it from the PDF first); alt becomes the image description."""
    P.imn += 1; i = f'{P.pid}_im{P.imn:03d}'; P.texts[i] = alt; P.speech[i] = alt
    assert (ROOT / 'images' / file).exists(), f'missing images/{file}'
    c = f' class="{cls}"' if cls else ''
    return f'<img{c} data-id="{i}" src="images/{file}" alt="{H.escape(alt)}">'

def field(kind='lined', label='', rows=4):
    """kind: lined (ruled box) | area (plain box) | line (one-line input). label is read by screen readers."""
    P.fn += 1; i = f'item-{P.fn}'; lab = f'<label class="sr-only" for="{i}">{H.escape(label)}</label>' if label else ''
    if kind == 'line': return f'{lab}<input id="{i}" data-activity-item="{i}" type="text" class="prx-field" autocomplete="off">'
    cls = 'prx-field prx-lined' if kind == 'lined' else 'prx-field'
    return f'{lab}<textarea id="{i}" data-activity-item="{i}" class="{cls}" rows="{rows}" spellcheck="true"></textarea>'

def section(*blocks, lesson=None, practice=False, stype='other', css='', answers=None):
    """Start a new reader section made of the given blocks (strings)."""
    if lesson: P.lesson = lesson
    body = '\n'.join(b for b in blocks if b); keys, mc, ms, opn = P.keys, P.mc, P.ms, P.open; P.keys, P.mc, P.ms, P.open = {}, {}, {}, False
    assert sum(map(bool, (keys, mc, ms))) <= 1, 'one reader activity per section: split typed answers, multiple choice and multi-select into separate sections'
    if opn and not (keys or mc or ms): stype = 'activity_open_ended_answer'; css += ACTIVITY_CSS   # written answers: Submit accepts any real text
    if keys or (opn and not (mc or ms)):
        if keys: stype = 'activity_fill_in_the_blank'
        css += '' if opn and not keys else ACTIVITY_CSS
        # the reader appends its verdict to aria-label, which would replace the hidden <label>; so name the field with aria-label too
        body = re.sub(r'(<label class="sr-only" for="(item-\d+)">(.*?)</label><(?:input|textarea) )', r'\1aria-label="\3" ', body)
    if answers:   # an activity whose key is window.correctAnswers (e.g. stype='activity_true_false': {row item id: 'V'})
        assert not (keys or mc or ms); keys = answers; css += ACTIVITY_CSS
    if mc: stype = 'activity_multiple_choice'; css += ACTIVITY_CSS
    if ms: stype = 'activity_multi_select'; css += ACTIVITY_CSS; mc = ms
    P.sections.append({'html': body, 'practice': practice, 'stype': stype, 'css': css, 'lesson': P.lesson, 'keys': keys, 'mc': mc})

# ---- blocks ----
def title(text, kicker=None, practice=False, level=1):
    el, i = T(text, tag='span') if practice else T(text, tag='h1' if not kicker else 'h2')
    P.toc.append((len(P.sections), text, i, level if not practice else 2))
    if practice: return f'<header class="b-page-title is-practice"><h1><img class="b-page-title-icon" src="{ICON["practice"]}" alt="">{el}</h1></header>'
    k = T(kicker, tag='h1', cls='b-page-title-kicker')[0] if kicker else ''
    return f'<header class="b-page-title">{k}{el}</header>'

def rule(practice=False): return f'<div class="b-page-rule{" is-practice" if practice else ""}" aria-hidden="true"></div>'

def keywords(words, label='Fjalët kyçe:'):
    return (f'<aside class="b-lesson-keywords" aria-label="Fjalët kyçe">{t(label, cls="b-lesson-keywords-label")}'
            f'{t(words, cls="b-lesson-keywords-words")}</aside>')

def panel(kind, heading=None, *body, toc=True):
    """kind: thought | questions | discussion | research | internet | glossary | deepen. body = blocks (items(), para(), field()…)."""
    head = ''
    if heading:
        el, i = T(heading, tag='h2', cls='b-rubric')
        if toc: P.toc.append((len(P.sections), heading, i, 2))
        head = f'<div class="b-lesson-thought-head"><img src="{ICON[kind]}" alt="">{el}</div>'
        return f'<aside class="b-lesson-thought{PANEL[kind]}">{head}\n' + '\n'.join(body) + '</aside>'
    return (f'<aside class="b-lesson-thought{PANEL[kind]}"><div class="b-lesson-thought-icon-only"><img src="{ICON[kind]}" alt=""><div>'
            + '\n'.join(body) + '</div></div></aside>')

def heading(kind, text):
    """Rubric heading without a box (e.g. Thello dijet above plain text)."""
    el, i = T(text, tag='h2', cls='b-rubric'); P.toc.append((len(P.sections), text, i, 2))
    return f'<div class="b-lesson-thought-head"><img src="{ICON[kind]}" alt="">{el}</div>'

def items(*qs):
    """Bullet list; each item 'text' or ('text','easy')."""
    return '<ul>' + ''.join(T(*q, tag='li')[0] if isinstance(q, tuple) else T(q, q, tag='li')[0] for q in qs) + '</ul>'

def questions(*qs, rows=2):
    """Questions the pupil answers in writing: each 'text' or ('text','easy'), followed by its own lined answer box.
    The section becomes the reader's open-ended activity (Submit button, sound, popup; any real text is accepted)."""
    out = ''; P.open = True
    for q in qs:
        q = q if isinstance(q, tuple) else (q, q)
        out += '<div class="p2-qa"><p class="p2-qa-text">' + t(*q) + '</p>' + field('lined', q[0], rows=rows) + '</div>'
    return out

def text(*paras): return '<div class="b-lesson-text">' + ''.join(paras) + '</div>'

def figure(file, alt, caption=None, wide=True):
    cap = T(caption, tag='figcaption')[0] if caption else ''
    return f'<figure class="b-lesson-figure{" is-wide" if wide else ""}">{img(file, alt)}{cap}</figure>'

def media(file, alt, *paras, reversed=False, caption=None, body=None):
    cap = T(caption, tag='figcaption')[0] if caption else ''
    inner = body if body is not None else '<div class="b-lesson-text">' + ''.join(paras) + '</div>'
    return f'<div class="b-lesson-media{" is-reversed" if reversed else ""}"><figure class="b-lesson-figure">{img(file, alt)}{cap}</figure>{inner}</div>'

def gallery(*figs, cols=3, mode=''):
    """figs: (file, alt, caption|None). mode: '' | 'is-contain' | 'is-natural'."""
    return (f'<div class="b-lesson-gallery {mode}" style="--cols:{cols}">' +
            ''.join(f'<figure class="b-lesson-figure">{img(f, a)}{T(c, tag="figcaption")[0] if c else ""}</figure>' for f, a, c in figs) + '</div>')

def task(*instruction, body=''):
    """A numbered practice task: instruction sentences (strings or (text, easy)), then body blocks."""
    ins = ' '.join(t(*s) if isinstance(s, tuple) else t(s, s) for s in instruction)
    return f'<div class="prx-step"><p class="prx-instruction">{ins}</p>\n<div class="prx-fields">{body}</div></div>'

def raw(html): return html

