    raw_t = (ROOT / 'content/toc.json').read_text(); toc = json.loads(raw_t)
    new_files = []
    for sids, pg in built:
        for d in (texts, speech):
            for k in [k for k in d if k.startswith(pg.pid + '_')]: del d[k]
        texts.update(pg.texts); speech.update(pg.speech)
        old = [p['href'] for p in spine if p['section_id'].startswith(pg.pid + '_')]
        spine = [p for p in spine if not p['section_id'].startswith(pg.pid + '_')]
        toc = [e for e in toc if not e.get('section_id', '').startswith(pg.pid + '_')]
        for f in old:
            if f[:-5] not in sids and (ROOT / f).exists(): (ROOT / f).unlink()
        # insert in page order: after the last entry whose page_number < this page (quizzes follow their page)
        pos = max([i for i, p in enumerate(spine) if p.get('page_number', 0) and p['page_number'] < pg.n] or [len(spine) - 1]) + 1
        while pos < len(spine) and 'page_number' not in spine[pos]: pos += 1
        spine[pos:pos] = [{'section_id': s, 'href': s + '.html', 'page_number': pg.n} for s in sids]
        for sec, title_, cid, level in pg.toc:
            toc.append({'section_id': sids[sec], 'href': sids[sec] + '.html', 'title': title_, 'chapter_id': cid, 'level': level})
        new_files += [s + '.html' for s in sids]
    order = {p['section_id']: i for i, p in enumerate(spine)}
    known = [e for e in toc if e.get('section_id') in order]; known.sort(key=lambda e: order[e['section_id']])
    toc = known + [e for e in toc if e.get('section_id') not in order]
    dump = lambda d, raw_: json.dumps(d, ensure_ascii=False, indent=2 if '\n  ' in raw_ else None) + ('\n' if raw_.endswith('\n') else '')
    (LANG / 'texts.json').write_text(dump(texts, (LANG / 'texts.json').read_text()))
    (LANG / 'speech_texts.json').write_text(dump(speech, (LANG / 'speech_texts.json').read_text()))
    (ROOT / 'content/pages.json').write_text(dump(spine, raw_p)); (ROOT / 'content/toc.json').write_text(dump(toc, raw_t))
    for i, p in enumerate(spine, 1):
        f = ROOT / p['href']; s = f.read_text()
        s2 = re.sub(r'(<meta name="page-section-id" content=")\d+(")', rf'\g<1>{i}\2', s, count=1)
        if s2 != s: f.write_text(s2)
    js = ("const fs=require('fs');const src=fs.readFileSync('book-design/rebuild-cache.cjs','utf8');"
          "const parse=eval('('+src.match(/function parse\\(s\\)\\{[\\s\\S]*?\\n?return \\{prefix[^}]*\\};\\}/)[0].replace('function parse','function')+')');"
          "const f='assets/offline-preloader.js';const c=parse(fs.readFileSync(f,'utf8'));"
          f"for(const k of {json.dumps(['./' + n for n in new_files])})if(!(k in c.value))c.value[k]='';"
          "for(const k of Object.keys(c.value))if(/^\\.\\/pg\\d+_sec\\d+\\.html$/.test(k)&&!fs.existsSync(k))delete c.value[k];"
          "fs.writeFileSync(f,c.prefix+JSON.stringify(c.value)+c.suffix);")
    subprocess.run(['node', '-e', js], check=True, cwd=ROOT)
    return len(spine)

