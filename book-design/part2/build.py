# ---- build ----
def build_page(n):
    global P
    P = Page(n); spec = SPECS / f'pg{n:03d}.py'
    exec(compile(spec.read_text(), str(spec), 'exec'), {k: v for k, v in globals().items() if not k.startswith('_')})
    out = []
    for k, s in enumerate(P.sections, 1):
        sid = f'{P.pid}_sec{k:03d}'
        sr = '' if '<h1' in s['html'] else f'<h1 class="sr-only">{H.escape(s["lesson"])}</h1>\n'
        page = HEAD.format(sid=sid, spec=spec.name, css=CSS + s['css'], sr=sr, prx=' prx' if s['practice'] else '', pcls=P.pid,
                           family='response' if s['practice'] else 'illustrated-lesson', stype=s['stype'],
                           sattr=(' data-correct-answers="' + H.escape(json.dumps(s['mc'])) + '"') if s['mc'] else '') + s['html'] + _tail(s)
        b = page[page.find('<main'):page.find('</main>')]
        for tag in ('div', 'aside', 'figure', 'section', 'ul', 'p'):
            assert b.count(f'<{tag}') == b.count(f'</{tag}>'), f'{sid}: unbalanced <{tag}>'
        (ROOT / f'{sid}.html').write_text(page); out.append(sid)
    ids = re.findall(r'id="(item-\d+)"', ''.join(s['html'] for s in P.sections)); assert len(ids) == len(set(ids))
    return out, P

